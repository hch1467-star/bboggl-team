const OUT_DIR = process.env.ZONE_OUT_DIR || path.join(ROOT, 'src', 'levels')

const W = 88
const H = 72
const VOID = -1

const heights = new Array(W * H).fill(VOID)
const entities = []
/**
 * ⚠️ **보물 자리는 이 파일이 아니라 실측이 정했습니다.**
 *
 * 아래 다섯 자리는 원래 이 파일이 "여기 두면 좋겠다"로 정한 값이었는데,
 * 나중에 `npm run secret` 으로 **주 동선에서 보이는지**를 재고 네 개를
 * 옮겼습니다(전부 주 동선에서 17~18m). 그런데 옮긴 것은 완성된 레벨
 * 파일이었고, **이 파일은 옛 자리 그대로 남아 있었습니다.**
 *
 * 즉 누군가 `npm run zone` 을 돌리는 순간 그 측정이 **조용히 되돌려집니다.**
 * 실제로 그 회차에 발견해서 맞췄습니다. 값을 두 곳에 두면 언젠가 갈라지고,
 * 갈라진 것을 알려 주는 것은 아무것도 없습니다.
 *
 * ⚠️ 그리고 그 "실측"도 한 번 틀렸습니다. **직선거리**로 재서 다섯 개가
 *    전부 "동선에서 17~18m"라고 통과했는데, 걸어야 하는 거리로 다시 재니
 *    18 · 18 · 24 · 32 · **48m** 였습니다. 48m 짜리는 봇의 곁길 예산(40m)을
 *    넘어서 **규칙상 영영 안 가는 자리**였고, 실제로 벤치 4판에서 4/4 미획득
 *    이었습니다. 이제 `npm run secret` 이 두 거리를 다 재고 예산을 검사합니다.
 */
const regions = []

/** 격자 좌표 -> 월드 좌표 (format.ts 의 cellToWorld 와 같은 식) */
function world(cx, cz) {
  return { x: (cx - W / 2 + 0.5) * 2, z: (cz - H / 2 + 0.5) * 2 }
}

function at(x, z) {
  if (x < 0 || z < 0 || x >= W || z >= H) return VOID
  return heights[z * W + x]
}

/** 사각 영역을 특정 높이로 채웁니다. (끝 좌표 포함) */
function rect(x0, x1, z0, z1, h) {
  for (let z = z0; z <= z1; z++) {
    for (let x = x0; x <= x1; x++) {
      if (x < 0 || z < 0 || x >= W || z >= H) continue
      heights[z * W + x] = h
    }
  }
}

/** 이름 붙은 구역. 새 구역에 들어서면 이름이 화면에 뜹니다. */
/**
 * `tint` 는 이 구역의 **지면 색조**(윗면·옆면 색에 채널별로 곱함)입니다.
 * 채도를 낮게 쓰는 이유와 검사는 format.ts `LevelRegion.tint` 주석 참고 —
 * 한 색 쪽으로 진하게 물들이면 그 색 예고가 그 구역에서만 묻힙니다.
 */
function region(name, x0, x1, z0, z1, hint, tint) {
  regions.push({ name, x0, x1, z0, z1, hint, tint })
}

function put(kind, cx, cz) {
  const { x, z } = world(cx, cz)
  entities.push({ kind, x, z, rotY: 0 })
}

