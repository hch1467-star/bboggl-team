/**
 * ⏱ **이 기계가 얼마나 느린가** — 프로브 공통 눈금
 *
 * ── 왜 만들었나 ────────────────────────────────────────────────────
 * 프로브 넷(`feel` · `pace` · `react` · `flank`)이 **한 번도 결과를 낸 적이
 * 없었습니다.** 7분을 줘도 끝나지 않아서 「안 도는 프로브」로 보였고, 그
 * 안의 검사는 전부 없는 것이나 마찬가지였습니다.
 *
 * 그런데 재 보니 **멈춘 것이 아니라 느린 것**이었습니다. 넷 다 진행 중이
 * 었고, `react` 는 이미 검사 둘을 통과시킨 상태였습니다.
 *
 * 하필 그 넷이 이 프로젝트의 미해결 질문들입니다:
 *   · `feel`  — 누른 뒤 게임이 **접수하기까지** (컨트롤 게임의 핵심 값)
 *   · `pace`  — 보스 구간 배분 (설계와 벤치가 반대로 나오는 자리)
 *   · `react` — 4색 정답 계산에 **사람의 반응 시간** 넣기
 *   · `flank` — 기둥 3(포지셔닝 보상)이 6~7%밖에 안 도는 문제
 *
 * ── 무엇이 문제였나 ────────────────────────────────────────────────
 * **침묵이 두 가지를 뜻했습니다.**
 *
 *     고장 난 침묵   — 어딘가에서 무한 대기. 그 자리를 고쳐야 합니다.
 *     일하는 침묵   — 그냥 오래 걸림. 기다리면 됩니다.
 *
 * 둘이 똑같이 보이니 아무도 기다리지 않았고, 그래서 넷이 조용히 죽어
 * 있었습니다. 이 저장소가 여러 번 한 일과 같은 처방입니다 —
 * **결과 하나를 갈래마다 나눠 셉니다**(궁수의 「0회」를 넷으로, `unseen`
 * 을 둘로, 「안 눌렀다」의 처방을 갈랐던 것처럼).
 *
 * ── 왜 이 기계에서만 이런가 ────────────────────────────────────────
 * 이 컨테이너에는 GPU 가 없습니다(SwiftShader 소프트웨어 렌더링). 그래서
 * **한 프레임이 0.2초쯤** 걸리고, 시뮬레이션 1초가 벽시계로 **10초를
 * 넘습니다.** 시뮬레이션 시간으로 짜인 프로브는 그 배율만큼 그대로
 * 느려집니다 — 게임 탓도 프로브 탓도 아닙니다.
 *
 * 이 저장소는 이미 그 배율을 재고 있었습니다(`playthrough.mjs` 의
 * `simPerWall`). 다만 **봇에만** 있었습니다. 여기로 올려 누구나 쓰게 합니다.
 */

/**
 * 이 기계가 **시뮬레이션 1초를 벽시계 몇 초에** 도는지 잽니다.
 *
 * @param page Playwright 페이지 (게임이 이미 `ready` 여야 합니다)
 * @param simSeconds 재는 데 쓸 시뮬레이션 시간(초). 짧으면 튀고, 길면
 *        측정 자체가 느려집니다. 기본 0.3초면 이 컨테이너에서 3~4초입니다.
 * @returns 벽시계초 ÷ 시뮬레이션초. 빠른 기계면 1 미만입니다.
 */
export async function simPerWall(page, simSeconds = 0.3) {
  return page.evaluate(async (want) => {
    const G = window.__game
    const t0 = G.state().simElapsed
    const w0 = Date.now()
    // ⚠️ 벽시계 상한을 둡니다 — 게임이 멈춰 있으면 여기서 영원히 기다립니다.
    const dl = w0 + 30000
    while (G.state().simElapsed - t0 < want && Date.now() < dl) {
      await new Promise((r) => setTimeout(r, 4))
    }
    const dSim = G.state().simElapsed - t0
    const dWall = (Date.now() - w0) / 1000
    return dSim > 0 ? dWall / dSim : -1
  }, simSeconds)
}

/**
 * ⏱ **「조용하다고 멈춘 것이 아닙니다」를 첫 줄에 적습니다.**
 *
 * 프로브가 쓸 시뮬레이션 시간을 스스로 신고하면(대략이면 충분합니다),
 * 이 기계의 배율을 곱해 **예상 벽시계 시간**을 찍어 줍니다.
 *
 * ⚠️ 이 줄은 **판정이 아닙니다.** 느린 것은 게임의 결함이 아니므로
 *    빨간불을 만들지 않습니다. 사람이 기다릴지 말지를 정하게 할 뿐입니다.
 *
 * @param ratio `simPerWall()` 이 낸 값
 * @param plannedSim 이 프로브가 쓸 시뮬레이션 시간(초) — 어림값
 */
export function announceSpeed(ratio, plannedSim, hint = '') {
  if (!(ratio > 0)) {
    console.log('  ⏱ 이 기계의 속도를 못 쟀습니다 (게임이 안 돌고 있을 수 있습니다)')
    return
  }
  const slow = ratio > 3
  let line =
    `  ⏱ 이 기계 — 시뮬레이션 1초 ≈ 벽시계 **${ratio.toFixed(1)}초**` +
    `${slow ? ' (GPU 없는 컨테이너입니다 — 정상)' : ''}`
  /**
   * ⚠️ 예상 시간은 **유도할 수 있을 때만** 적습니다.
   *
   * 프로브마다 쓰는 시뮬레이션 시간이 다른데, 그걸 제가 어림해서 적으면
   * 그건 잰 값이 아니라 **지어낸 값**입니다. 이 저장소가 계속 피해 온
   * 것이 그것입니다 — 프로브 자신의 상수에서 나오지 않는 숫자는 안 씁니다.
   */
  if (plannedSim > 0) {
    const mins = (plannedSim * ratio) / 60
    line +=
      `\n     이 프로브가 쓰는 시뮬레이션 시간 ≈ ${plannedSim.toFixed(0)}초` +
      ` → **예상 ${mins < 1 ? `${Math.ceil(mins * 60)}초` : `${mins.toFixed(0)}분`}**`
  }
  if (slow) line += `\n     조용해도 **멈춘 것이 아닙니다.**`
  if (hint) line += ` ${hint}`
  console.log(line)
}
