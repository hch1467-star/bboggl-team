/**
 * 시드 기반 난수 생성기 (mulberry32).
 *
 * 설계 근거: Math.random()을 쓰면 절대 안 되는 이유가 두 가지 있습니다.
 *  1) 절차적 던전 생성 — 같은 시드로 항상 같은 맵이 나와야 "시드 공유"가 가능합니다.
 *  2) 버그 재현 — 랜덤 아이템/랜덤 스폰에서 버그가 나면 시드 없이는 재현이 불가능합니다.
 *
 * 용도별로 RNG 인스턴스를 분리하는 것도 중요합니다. 맵 생성 RNG와 전투 RNG가
 * 같은 스트림을 공유하면, 전투 중 주사위를 한 번 더 굴린 것만으로 맵이 바뀌어 버립니다.
 */
export class Rng {
  private state: number
  /** 씨앗 자체 — `at()` 이 스트림과 **따로** 쓰려고 들고 있습니다. */
  private readonly seed: number

  constructor(seed: number) {
    // 0 시드는 mulberry32에서 품질이 나빠서 항상 홀수 오프셋을 더합니다.
    this.seed = (seed | 0) + 0x6d2b79f5
    this.state = this.seed
  }

  /**
   * 🎲 **스트림을 다른 씨앗으로 되돌립니다** (프로브가 «판을 여러 번» 볼 수 있게).
   *
   * ── 왜 생겼나 ────────────────────────────────────────────────────
   * 보스가 같은 패턴을 연달아 내는 비율을 재다가 막혔습니다. 실측 28%,
   * 표가 말하는 기대치 13% — 3σ 짜리 어긋남인데, **표본이 하나뿐**이라
   * 「진짜 어긋남」인지 「그 판이 그랬을 뿐」인지 가릴 수가 없었습니다.
   * `combatRng` 는 씨앗이 1337 로 고정이라, 같은 프로브를 백 번 돌려도
   * **같은 한 판**입니다.
   *
   * 이 저장소가 판마다 늘 말하던 것(*"한 판으로 처방하지 마십시오"*)이
   * **난수 자체에도** 해당한다는 것을 그때 알았습니다. 계측기가 여러 판을
   * 보려면 스트림을 갈아 끼울 손잡이가 있어야 합니다.
   *
   * ⚠️ 게임 코드에서는 **부르지 않습니다.** 부르는 순간 「같은 시드면 같은
   *    판」이라는 이 파일 머리말의 약속이 깨집니다. 프로브 전용입니다.
   */
  reseed(seed: number): void {
    this.state = (seed | 0) + 0x6d2b79f5
  }

  /** 0 이상 1 미만 */
  next(): number {
    let t = (this.state += 0x6d2b79f5)
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }

  /**
   * 🔑 **자리에서 바로 뽑는 값** — 스트림을 굴리지 않습니다.
   *
   * ── 왜 따로 필요한가 ──────────────────────────────────────────────
   * `next()` 는 **부른 순서**가 값을 정합니다. 그래서 지도 위에 무언가를
   * 흩뿌릴 때 이걸 쓰면, 칸을 하나 늘리거나 훑는 순서를 바꾸는 것만으로
   * **그 뒤가 전부 밀립니다.** 지도를 서쪽으로 두 칸 넓혔더니 동쪽 폐허가
   * 통째로 달라지는 식입니다 — 시드를 고정한 의미가 없어집니다.
   *
   * 그래서 배치용으로는 **좌표를 열쇠로 넣어** 값을 만듭니다. 같은 칸이면
   * 언제 물어도 같은 값이고, 이웃 칸과는 상관이 없습니다. (마인크래프트가
   * 청크를 어디서부터 만들든 같은 세계가 나오는 것과 같은 이유입니다.)
   *
   * ⚠️ **판정에 쓰지 마십시오.** 같은 열쇠면 늘 같은 값이라, 공격 명중처럼
   *    "매번 새로 굴려야 하는" 것에 쓰면 결과가 굳어 버립니다.
   */
  at(key: number): number {
    let t = (key | 0) + this.seed
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }

  /** min 이상 max 미만 */
  range(min: number, max: number): number {
    return min + this.next() * (max - min)
  }

  /** min 이상 max 이하 (정수) */
  int(min: number, max: number): number {
    return Math.floor(this.range(min, max + 1))
  }

  /** 확률 p(0~1)로 true */
  chance(p: number): boolean {
    return this.next() < p
  }

  pick<T>(items: readonly T[]): T {
    return items[Math.floor(this.next() * items.length)]
  }

  /** 가중치 기반 선택 — 루트 테이블(아이템 등급 추첨)의 기본 연산입니다. */
  weighted<T>(items: readonly T[], weightOf: (item: T) => number): T {
    let total = 0
    for (const it of items) total += weightOf(it)
    let roll = this.next() * total
    for (const it of items) {
      roll -= weightOf(it)
      if (roll <= 0) return it
    }
    return items[items.length - 1]
  }
}

/** 전역 스트림 — 나중에 던전/전투/루트로 분리합니다. */
export const combatRng = new Rng(1337)

/**
 * ── 🎨 **연출 전용 스트림** — 불꽃 흩뿌림 · 숫자 흔들림 ─────────────
 *
 * ── 왜 장식에도 씨앗이 필요한가 ────────────────────────────────────
 * 위 두 가지 근거(맵 시드 공유 · 버그 재현)는 **판정**의 이야기라, 이
 * 저장소는 오랫동안 연출은 예외로 두고 `Math.random()` 을 그대로 썼습니다.
 * 그런데 이 저장소에는 세 번째 이유가 생겼습니다:
 *
 *   **3) 스크린샷 비교** — 이 저장소의 검사 상당수가 *"같은 시각이면
 *      같은 그림"* 위에 서 있습니다(`npm run depth` · `gear` 의 등급
 *      불티 · `verify` 의 사진들). 타격 한 번에 불꽃이 무작위로 흩어지면
 *      전투 장면은 **원리적으로 비교할 수 없습니다.**
 *
 * 실제로 이번 라운드에 등급 불티를 만들 때 *"무작위 방출기를 쓰지 않는다"*
 * 를 설계 원칙으로 적어야 했고(`render/gearAura.ts`), 깊이 검사에서는
 * 픽셀 비교를 세우느라 네 번을 되돌렸습니다. 연출이 재현되지 않으면
 * **계측기를 만들 수 없습니다.**
 *
 * ⚠️ **전투 스트림과 분리합니다.** 같이 쓰면 *"불꽃이 한 번 더 튀었다"*
 *    는 이유만으로 적의 주사위가 달라집니다 — 위 파일 머리말이 경고하는
 *    바로 그것입니다.
 */
export const vfxRng = new Rng(0x5eed)

/**
 * 🔊 **소리 전용 스트림** — 마디 강세 · 노이즈 재생 시작점.
 *
 * 같은 이유로 나눕니다: 북을 한 번 더 치는 것이 전투 주사위를 밀면 안
 * 됩니다. `npm run audio` 도 *"같은 입력이면 같은 소리"* 를 재는 쪽이
 * 훨씬 쉬워집니다.
 */
export const audioRng = new Rng(0xa0d10)

/**
 * 🏛 **배치 전용 스트림** — 폐허 잔해가 어디에 서는가(render/props.ts).
 *
 * 이쪽은 거의 전부 `at(좌표)` 로 씁니다. 지도를 손봐도 이미 있던 폐허가
 * 그 자리에 남아야 하기 때문입니다 — 위 `at()` 주석에 그 이유가 있습니다.
 */
export const propRng = new Rng(0xb00c)
