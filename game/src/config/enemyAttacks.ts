/**
 * 🔁 **갚을 수 있는 창**(초) — 이 공격이 헛쳤을 때 적이 무방비인 시간.
 *
 * 이 한 줄짜리 함수를 굳이 두는 이유는, 같은 판단이 **두 곳**에서 필요하기
 * 때문입니다: 실제로 후딜을 세우는 enemyAI 와, 그 창이 충분한지 계산하는
 * `punish.ts` 입니다. 두 곳에 `atk.whiffRecovery ?? atk.recovery` 를 각각
 * 적어 두면 한쪽만 고치는 날 **프로브가 게임을 안 재게 됩니다** —
 * 이 저장소가 이번 세션에 열 번 밟은 함정이 정확히 그것입니다.
 */
export function openingOf(atk: EnemyAttackDef): number {
  return atk.whiffRecovery ?? atk.recovery
}

export function attacksFor(kind: number): EnemyAttackDef[] {
  return ATTACKS_BY_KIND[kind] ?? GRUNT_ATTACKS
}

/** 패턴을 인덱스로 저장하기 위한 조회 — ECS는 숫자만 담을 수 있습니다. */
export function attackAt(kind: number, index: number): EnemyAttackDef {
  const list = attacksFor(kind)
  return list[Math.min(Math.max(index, 0), list.length - 1)]
}
