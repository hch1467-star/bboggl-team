/**
 * 적 종류 표 — 종류 하나당 한 줄.
 *
 * ── 왜 이 파일이 생겼는가 ───────────────────────────────────────────
 * 지금까지 코드 곳곳에 `isBoss ? BOSS : GRUNT` 가 흩어져 있었습니다.
 * 불리언은 **종류가 정확히 둘일 때만** 성립합니다. 셋째가 생기는 순간
 * 그 조건문들은 전부 조용히 **"보스가 아니면 잡몹"** 이라고 잘못 답합니다.
 * 오류도 안 나고 화면도 그럴듯해서, 얽는 자가 잡몹의 체력·속도·공격을
 * 그대로 쓰고 있어도 알아채기 어렵습니다.
 *
 * 그래서 새 적을 추가하기 **전에** 불리언을 표로 바꿨습니다.
 * 새 적을 하나 더 넣을 때 손대야 하는 곳이 이 파일 한 줄이 되도록.
 *
 * (Unity 이식 노트: 이 표의 한 항목이 EnemyDefinition.asset 하나가 됩니다.)
 */
import { ARCHER, BINDER, BOSS, CHARGER, DRAGGER, GRUNT } from './balance'
import { EnemyKind } from '../core/components'

/**
 * 모든 종류가 공통으로 갖는 수치.
 *
 * `keepDistance` 만 선택 항목입니다 — 근접 적에게는 의미가 없고,
 * 0으로 두면 "거리 0을 유지한다"는 뜻이 되어 헷갈립니다.
 */
export interface EnemyDef {
  /** 저장·표시용 식별자 */
  id: string
  name: string
  maxHp: number
  radius: number
  height: number
  moveSpeed: number
  turnSpeedDeg: number
  backReactionDelay: number
  aggroRange: number
  attackRange: number
  attackCooldown: number
  windup: number
  active: number
  recovery: number
  damage: number
  attackArcDeg: number
  attackReach: number
  knockback: number
  hurtStagger: number
  /** 몸 색. 예고 4색과 겹치면 안 됩니다(아래 주석 참고). */
  color: number
  /**
   * 이 거리보다 가까우면 **물러납니다.** 없으면 근접형입니다.
   * 원거리 적에게 이게 없으면 그냥 걸어 들어와 약한 잡몹이 됩니다.
   */
  keepDistance?: number
  /**
   * ── 연계 — "이 패턴 뒤에는 저 패턴이 따라붙는다" ──────────────────
   *
   * 지금까지 연계는 **보스에만** 있었습니다(bossPhases.ts). 그래서 잡몹
   * 구간에서 플레이어가 배우는 것은 *"적이 휘두르고 나면 후딜은 공짜"* 인데,
   * 보스에 와서 그게 거짓이라는 걸 처음 배웁니다. **가르치는 순서가
   * 거꾸로입니다.**
   *
   * NRFTW 의 보스 워릭 공략이 정확히 이 문법을 설명합니다:
   * *"가끔 이걸 두 번째 공격으로 잇는다. **반격을 커밋하기 전에 후속을
   * 확인하라.**"* 그 게임에서는 잡몹이 이 문법을 미리 가르칩니다.
   *
   * 키는 패턴 id, 값은 뒤따를 패턴 id 입니다.
   */
  chains?: Record<string, string>
  /**
   * **사거리 밖에서 다가올 때만** 곱하는 속도 배율. 없으면 1(접근·전투 속도가 같음).
   *
   * ── 왜 "접근 속도"를 따로 두는가 ────────────────────────────────
   * `moveSpeed` 하나로는 두 가지 다른 질문에 같은 답을 강요합니다:
   *   · 전투 중 얼마나 재빠르게 붙었다 떨어지는가 (손맛·가독성)
   *   · **도망치는 플레이어를 따라잡을 수 있는가** (도망이 답인가 아닌가)
   * 지금은 둘이 붙어 있어서, 전투에서 편한 속도를 고르면 추격이 사라지고
   * 추격이 되는 속도를 고르면 전투가 정신없어집니다.
   *
   * ── 왜 전부가 아니라 한 종류에만 주는가 ────────────────────────
   * 바로 아래(enemyAI.ts 추격 블록)에 *"잡몹이 빨라지면 '먼저 뭘 죽일까'가
   * 사라지고 모두가 동시에 얼굴 앞에 도착한다"* 고 적어 두었습니다.
   * 그 말은 지금도 맞습니다 — **전부**에 주면 그렇게 됩니다.
   * 하지만 **하나**에만 주면 반대가 됩니다: 나머지가 걸어오는 사이 하나가
   * 먼저 닿으므로, "먼저 뭘 답할까"가 오히려 또렷해집니다.
   * (엘든 링의 개·늑대가 이 자리입니다. 무리 전체가 빠른 게 아니라 개만 빠릅니다.)
   *
   * ── ⚠️ 지금은 **아무도 안 씁니다** (달려드는 자에게 줬다가 되돌렸습니다) ──
   * "사거리 밖에서만 걸리니 전투는 안 변한다"는 추론이 틀렸다는 것을 3판
   * 벤치가 보여 줬습니다. 이 배율은 **교전이 시작되는 거리**를 바꾸고,
   * 그 거리가 예고의 생사를 정합니다 — 빨리 붙으면 코앞에서 예고를 시작하고,
   * 긴 예고(1.4초)는 그 자리에서 매번 끊깁니다(판정 3회 → **0회**).
   *
   * 그래서 이 값을 쓸 수 있는 적은 **예고가 짧은 적**입니다. 필드를 남겨 두는
   * 이유가 그것이고, 쓸 때는 반드시 `예고 → 판정 (끊김%)` 을 같이 봐야 합니다.
   * 근거 전문은 balance.ts 의 CHARGER 주석에 있습니다.
   */
  approachSpeedScale?: number
  /**
   * 처치했을 때 주는 불티.
   *
   * **위험 대비**로 매깁니다. 얽는 자·끄는 자는 체력이 낮아 죽이기는 쉽지만,
   * 살려두면 전투 전체가 어려워집니다. 그래서 잡몹보다 많이 줍니다 —
   * "먼저 뭘 죽일까"라는 판단에 **보상까지 얹어** 방향을 분명히 합니다.
   */
  /**
   * 강인도. 이만큼 깎이면 무너집니다.
   *
   * 기준: 롱소드 기본 콤보 3타의 강인도 피해 합이 약 30입니다.
   *   잡몹 30    — 한 콤보를 온전히 넣으면 무너짐
   *   특수 20    — 더 쉽게 끊김(원거리 적을 끊는 건 쉬워야 함)
   *   보스 105   — 세 콤보 이상. 예고 중에 끊으면 훨씬 빨라집니다.
   */
  poiseMax: number
  ember: number
  /** 타격했을 때의 손맛 배율 — 큰 적일수록 크게 */
  hitstop: number
  trauma: number
  heavy: boolean
}

