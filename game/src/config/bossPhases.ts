/** 지금 체력 비율에 해당하는 페이즈 번호(0부터). */
export function phaseForHp(ratio: number): number {
  let phase = 0
  for (let i = 1; i < BOSS_PHASES.length; i++) {
    if (ratio < BOSS_PHASES[i].enterBelow) phase = i
  }
  return phase
}

export function bossPhase(index: number): BossPhaseDef {
  return BOSS_PHASES[Math.min(Math.max(index, 0), BOSS_PHASES.length - 1)]
}
