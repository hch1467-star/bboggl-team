export interface BossPhaseDef {
  name: string
  /**
   * 체력 비율이 이 값 **아래로** 내려가면 이 페이즈로 넘어갑니다.
   * 첫 페이즈는 1(=시작부터)입니다.
   */
  enterBelow: number
  /**
   * 공격 사이 쿨다운 배율. 작을수록 쉴 틈이 없어집니다.
   * **난이도를 올리는 주 손잡이는 여기입니다.**
   */
  cooldownScale: number
  /**
   * 선행동작(예고) 배율. 1에 가깝게 유지합니다 — 위 설계 노트 3번 참고.
   * 손맛을 위한 미세 조정 이상으로는 절대 내리지 않습니다.
   */
  windupScale: number
  /** 패턴 선택 가중치 덮어쓰기 (패턴 id → 가중치). 없으면 원래 값을 씁니다. */
  weights?: Record<string, number>
  /**
   * 연계 — 이 패턴의 후딜이 끝나면 **쿨다운 없이 곧바로** 저 패턴을 겁니다.
   * 예고는 정상적으로 다 나옵니다. 사라지는 건 "쉬는 시간"뿐입니다.
   */
  chains?: Record<string, string>
  /** 전환 배너 */
  banner: string
  desc: string
}

