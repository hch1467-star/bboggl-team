/**
 * 보스 페이즈 — 체력 구간마다 **싸우는 법이 바뀝니다.**
 *
 * ── 왜 페이즈가 필요한가 ──────────────────────────────────────────
 * 지금까지 보스는 처음부터 끝까지 같은 패턴 풀을 같은 확률로 돌렸습니다.
 * 그러면 체력 420이라는 숫자는 **"같은 것을 몇 번 더 반복하는가"** 일 뿐입니다.
 * 30초짜리 전투를 60초로 늘려도 배우는 것은 늘지 않습니다.
 *
 * 참고한 것: 로스트아크 보스는 대부분 2~3페이즈이고, 체력 임계값에서 넘어갑니다.
 * 플레이어들이 좋아한다고 말하는 지점과 싫어한다고 말하는 지점이 뚜렷했습니다.
 *
 *   좋아함 — 규칙이 분명하고, 실수하면 확실히 아프고, **패턴을 외울 수 있다**
 *   싫어함 — 무작위가 과하고, 예고가 불분명하고, **미리 알 수 없는 조건이 겹친다**
 *
 * 그래서 이 시스템의 규칙을 셋으로 못박았습니다:
 *
 *   1. **전환은 결정적입니다.** 체력 비율 하나로만 넘어갑니다. 시간도, 확률도 아닙니다.
 *   2. **전환은 무시할 수 없게 보입니다.** 무적 + 넉백 + 배너 + 소리.
 *      "언제 바뀌었지?"가 나오면 안 됩니다.
 *   3. **예고 시간은 거의 줄이지 않습니다.** ← 이게 가장 중요한 판단입니다.
 *
 * ── 3번을 고집하는 이유 ───────────────────────────────────────────
 * 난이도를 올리는 가장 쉬운 손잡이는 "예고를 짧게"입니다. 그리고 그건
 * DESIGN.md 기둥 2의 판단 기준을 **정면으로 위반**합니다:
 *
 *   > 죽었을 때 "내가 못 봤네"가 아니라 "내가 못 피했네"라고 말해야 한다.
 *
 * 예고를 줄이면 정확히 "못 봤네"로 갑니다. 그래서 **줄이면 안 되는 것은
 * 예고 시간이고, 줄여야 하는 것은 쉬는 시간**입니다.
 * 페이즈가 올라갈수록 공격과 공격 사이의 빈 시간이 사라지고, 연계가 붙습니다.
 * 모든 공격은 끝까지 완전한 예고를 갖습니다 — 다만 쉴 틈이 없어질 뿐입니다.
 *
 * ── 연계(chain)가 이 시스템의 핵심입니다 ──────────────────────────
 * 숫자만 키우는 페이즈(피해 +30%)는 플레이어에게 새로 배울 것을 주지 않습니다.
 * 우리에겐 이미 **4색**이라는 어휘가 있으니, 페이즈마다 **색의 조합**을 하나씩
 * 추가하는 편이 훨씬 강합니다. 조합은 새 규칙이 아니라 이미 아는 규칙 둘을
 * 붙인 것이라, 외울 수 있으면서도 즉시 어렵습니다.
 *
 * 특히 🔵 파랑은 지금까지 **설계와 실제가 어긋나 있었습니다.**
 * 파랑의 존재 이유는 "맞으면 묶여서 **다음 공격을 못 피한다**"인데,
 * 실제로는 쿨다운(1.5초)과 속박(1.6초)이 비슷해서 다음 공격이
 * 올 때도 있고 안 올 때도 있었습니다. 2페이즈의 `boss_bind → boss_cleave`
 * 연계가 그 약속을 처음으로 지키게 만듭니다.
 */

